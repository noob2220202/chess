// Builds the mini-board illustration for every card from its interactive demo:
// the demo is solved, and the pieces, arrows and highlights of that solution are
// cropped around the action into src/assets/cardArt.ts.
// usage: node scripts/gen-card-art.mjs
import fs from 'node:fs';
import { CARDS, CARD_ORDER, cloneState, demoAct, demoState, solveDemo } from '../../engine/src/index.ts';

const f = (x) => x & 7, r = (x) => x >> 3;

function snapshot(s) {
  const m = new Map();
  s.board.forEach((p, i) => { if (p) m.set(p.id, { sq: i, type: p.type, color: p.color, status: { ...p.status } }); });
  return m;
}
const active = (p, ply, st) => (p.status[st] ?? 0) > ply;

function art(id) {
  const def = CARDS[id];
  const s0 = demoState(id);
  const sol = solveDemo(s0, def.demo.goal);
  if (!sol) throw new Error(`demo for ${id} has no solution`);

  // Play leading card actions to get the frame shown in the picture.
  let s1 = cloneState(s0);
  let i = 0;
  const marks = [];
  for (; i < sol.length && 'card' in sol[i]; i++) {
    for (const x of sol[i].sel) marks.push([x, 'target']);
    demoAct(s1, sol[i]);
  }
  // Remaining actions are moves (possibly with more cards in between).
  const arrows = [];
  let s2 = cloneState(s1);
  for (; i < sol.length; i++) {
    const a = sol[i];
    if ('move' in a) arrows.push([a.move.from, a.move.to, 'move']);
    else for (const x of a.sel) marks.push([x, 'target']);
    demoAct(s2, a);
  }

  const before = snapshot(s0), mid = snapshot(s1), after = snapshot(s2);
  const pieces = [];
  for (const [pid, p] of mid) {
    const was = before.get(pid);
    let flag = '';
    if (!was) flag = 'new';
    else if (was.type !== p.type || was.color !== p.color) flag = 'changed';
    if (was && was.sq !== p.sq) arrows.push([was.sq, p.sq, 'card']);
    for (const st of ['frozen', 'shield', 'disarmed']) {
      const now = (p.status[st] ?? 0) > s1.ply, then = was ? (was.status[st] ?? 0) > s0.ply : false;
      if (now && !then) marks.push([p.sq, st]);
    }
    pieces.push([p.sq, p.color + p.type, flag]);
  }
  for (const [pid, p] of before) if (!mid.has(pid)) { pieces.push([p.sq, p.color + p.type, 'gone']); marks.push([p.sq, 'gone']); }
  // Pieces that appear only after the moves (turn-start reinforcements, promotions in place).
  for (const [pid, p] of after) {
    const m = mid.get(pid);
    if (!m && !before.has(pid)) { pieces.push([p.sq, p.color + p.type, 'new']); marks.push([p.sq, 'new']); }
    else if (m && m.type !== p.type) marks.push([p.sq, 'promote']);
  }
  for (const e of s1.effects) if (e.square !== undefined) marks.push([e.square, 'zone']);

  // Crop around everything that happens.
  const focus = [...arrows.flatMap((a) => [a[0], a[1]]), ...marks.map((m) => m[0]), ...pieces.filter((p) => p[2]).map((p) => p[0])];
  if (!focus.length) return null; // global effects: the emblem says it better
  let x0 = Math.min(...focus.map(f)), x1 = Math.max(...focus.map(f));
  let y0 = Math.min(...focus.map(r)), y1 = Math.max(...focus.map(r));
  // Pull in nearby context (attackers, the rook a card refers to...) while the crop stays readable.
  const others = pieces.map((p) => p[0]).filter((x) => !focus.includes(x));
  const cx = (x0 + x1) / 2, cy = (y0 + y1) / 2;
  others.sort((a, b) => Math.hypot(f(a) - cx, r(a) - cy) - Math.hypot(f(b) - cx, r(b) - cy));
  for (const x of others) {
    const nx0 = Math.min(x0, f(x)), nx1 = Math.max(x1, f(x)), ny0 = Math.min(y0, r(x)), ny1 = Math.max(y1, r(x));
    if (Math.max(nx1 - nx0, ny1 - ny0) + 1 <= 6) { x0 = nx0; x1 = nx1; y0 = ny0; y1 = ny1; }
  }
  const n = Math.min(8, Math.max(4, x1 - x0 + 1, y1 - y0 + 1) + (Math.max(x1 - x0, y1 - y0) < 5 ? 1 : 0));
  const fit = (lo, hi) => { let a = Math.round((lo + hi) / 2 - (n - 1) / 2); return Math.max(0, Math.min(8 - n, a)); };
  const fx = fit(x0, x1), fy = fit(y0, y1);
  const inside = (x) => f(x) >= fx && f(x) < fx + n && r(x) >= fy && r(x) < fy + n;
  const rel = (x) => [f(x) - fx, r(x) - fy];
  return {
    n,
    pieces: pieces.filter((p) => inside(p[0])).map(([x, t, fl]) => [...rel(x), t, fl].filter((v) => v !== '')),
    arrows: arrows.filter((a) => inside(a[0]) && inside(a[1])).map(([a, b, k]) => [...rel(a), ...rel(b), k]),
    marks: [...new Map(marks.filter((m) => inside(m[0])).map((m) => [`${m[0]}:${m[1]}`, m])).values()].map(([x, k]) => [...rel(x), k]),
    light: (fx + fy) % 2 === 1,
  };
}

const out = {};
let skipped = 0;
for (const id of CARD_ORDER) {
  const a = art(id);
  if (a) out[id] = a; else skipped++;
}
const src = `// Generated by scripts/gen-card-art.mjs from each card's demo. Do not edit.
// [file, rank] are relative to the crop; rank 0 is the bottom row.
export interface CardArt {
  n: number;
  /** Bottom-left square of the crop is light. */
  light: boolean;
  pieces: Array<[number, number, string] | [number, number, string, 'new' | 'changed' | 'gone']>;
  arrows: Array<[number, number, number, number, 'move' | 'card']>;
  marks: Array<[number, number, 'target' | 'gone' | 'new' | 'promote' | 'zone' | 'frozen' | 'shield' | 'disarmed']>;
}
export const CARD_ART: Record<string, CardArt> = ${JSON.stringify(out)};
`;
fs.writeFileSync(new URL('../src/assets/cardArt.ts', import.meta.url), src);
console.log(`wrote art for ${Object.keys(out).length} cards (${skipped} use the emblem only), ${src.length} bytes`);
